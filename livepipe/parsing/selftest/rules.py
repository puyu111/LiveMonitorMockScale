"""livepipe.parsing.selftest.rules — 从 parse_live_comments.py 拆出的同源实现。"""

from __future__ import annotations

import sys

from ..text.classify import classify_line



def _selftest_rules() -> bool:
    """行文本规则的断言：等级徽章剥除边界 + 纯数字用户名（真实语料里都有反例）。"""
    cases = [
        # 徽章被 OCR 并进正文块时，剥完剩下的数字**是用户名**（抖音昵称 `1221` 真存在）
        ("徽章+纯数字昵称", "2 1221：好帅哦大哥哥", ("comment", ("1221", "好帅哦大哥哥")), False),
        # 昵称首位的数字不能被当徽章啃掉（旧正则剥成了 '喜'）
        ("昵称首位数字", "7喜：好", ("comment", ("7喜", "好")), False),
        # 没剥到徽章 ⇒ 前串纯数字仍按「徽章在、用户名丢了」⇒ 匿名，别把徽章当名字
        ("无徽章可剥的纯数字前串", "111：这是要漂移吗？", ("comment", (None, "这是要漂移吗？")), False),
        ("分隔符徽章", "2。hubvg:", ("comment", ("hubvg", "")), False),
        ("普通徽章+昵称", "1 时死你: 真帅啊", ("comment", ("时死你", "真帅啊")), False),
        ("通知行", "灵** 赞了直播", ("drop", "提示或通知"), False),
        # OCR 会把行首的「加」吃掉（实测 '加入了直播间' → '入了直播间'）；少认这一条，
        # 截断的通知就会漏成「用户名丢了的评论」
        ("通知行（行首被 OCR 吃掉）", "入了直播间", ("drop", "提示或通知"), False),
        # 带几何（徽章列已被 group_rows 丢掉）⇒ 前串纯数字只能是昵称；徽章菱形读成点也要剥掉
        ("几何路径：纯数字昵称", "1221：好帅哦大哥哥", ("comment", ("1221", "好帅哦大哥哥")), True),
        ("几何路径：徽章残留的点", "。hubvg:", ("comment", ("hubvg", "")), True),
        ("几何路径：只剩冒号", "：帅", ("comment", (None, "帅")), True),
        # 微博 App 的系统行：横幅（左半被折行判据丢、右半只剩药丸）+ 通知 + 开播公告。
        # 都**没有冒号**，所以那套按短语认抖音通知的 _NOTICE_RE 一条也认不出来。
        ("微博：横幅右侧药丸", "我也上榜", ("drop", "系统行"), True),
        ("微博：横幅正文", "恭喜海岸0030在助力榜飙升到第5名", ("drop", "系统行"), True),
        ("微博：进房通知", "甜甜蜜995通过直播预约进入直播间", ("drop", "系统行"), True),
        ("微博：进房通知（两行并成一行）",
         "画危鸭通过直播预约进入直播间用户4003695765通过直播预约进入直播间",
         ("drop", "系统行"), True),
        ("微博：开播公告（折行碎片）",
         "欢迎使用微博直播服务。微博直播禁止包含色情、违", ("drop", "系统行"), True),
        ("微博：开播公告（另一块碎片）",
         "物袋按钮，请勿私下交易，请谨慎判断以防人身财产损", ("drop", "系统行"), True),
        # **有冒号就不能连坐** —— 正文里写「进入直播间」是正常评论（抖音实测无害）。
        ("有冒号时系统短语不算数", "画危鸭：我终于进入直播间", ("comment", ("画危鸭", "我终于进入直播间")), True),
    ]
    bad = [n for n, line, want, geo in cases
           if classify_line(line, badge_column_excluded=geo) != want]
    if bad:
        print(f"[selftest] 行文本规则断言失败：{bad}", file=sys.stderr)
        return False
    # 微博「榜N」药丸（平台档案 rank_pill=true）：药丸跟在昵称右边，切下来丢掉，
    # 昵称与正文各归各位。每条都对应语料里量到的形状（见 _RANK_PILL_RE）。
    pill_cases = [
        ("药丸+冒号", "甜甜蜜995榜九：厉害呀", ("comment", ("甜甜蜜995", "厉害呀"))),
        # 冒号被 OCR 吃掉 —— 这正是用户报的那类：旧行为里整行落进续行，昵称丢了
        ("药丸+冒号丢了", "用户6861943086榜二这车这么稳", ("comment", ("用户6861943086", "这车这么稳"))),
        ("药丸+冒号丢了（另一条）", "爱笑的呈呈酱榜五这前脸一出来，我直接好家伙",
         ("comment", ("爱笑的呈呈酱", "这前脸一出来，我直接好家伙"))),
        # 行首就是药丸：昵称那块被 OCR 整块吃掉 ⇒ 匿名评论，正文照收（实测 243 行）
        ("药丸在行首", "榜三奇瑞是真的在听用户意见啊", ("comment", (None, "奇瑞是真的在听用户意见啊"))),
        # 名次那截被吃掉，只剩一个「榜」（实测 825 行）
        ("名次被吃掉的药丸", "幸运女神的小新榜这性能", ("comment", ("幸运女神的小新", "这性能"))),
        ("名次被吃掉且无正文", "用户6861943086榜", ("comment", ("用户6861943086", ""))),
        # 「来了」收尾的是真评论（_ENTER_RE 对药丸面板不适用，实测 199 行）
        ("药丸+来了收尾", "幸运女神的小新榜八秋名山女车神来了",
         ("comment", ("幸运女神的小新", "秋名山女车神来了"))),
        # 名次只有一个字：多啃一位就会吃掉正文首字
        ("名次后紧接正文首字", "画危鸭榜二一小时后就可以知道价格了",
         ("comment", ("画危鸭", "一小时后就可以知道价格了"))),
        ("名次八+正文十八段", "昵称不能为空513榜八十八段弯道，跑遍全国了",
         ("comment", ("昵称不能为空513", "十八段弯道，跑遍全国了"))),
        # 正文里带数字时，数字是正文的（早期 _RANK_PILL_RE 写成 […\d]* 会把它们吞掉）
        ("正文以数字开头", "幸运女神的小新榜618是不是还有活动啊",
         ("comment", ("幸运女神的小新", "618是不是还有活动啊"))),
        ("正文是 12 个 6", "万物0020榜四666666666666", ("comment", ("万物0020", "666666666666"))),
        ("正文是不带分隔的点数", "用户6861943086榜一011", ("comment", ("用户6861943086", "011"))),
        # 冒号在「榜」之前 ⇒ 冒号才是分隔符，正文里的「榜」不许切
        ("正文里的榜", "画危鸭：我也上榜了", ("comment", ("画危鸭", "我也上榜了"))),
        # 横幅右侧那个系统药丸（整行只有它）⇒ 系统行，不是匿名评论
        ("系统药丸", "我也上榜", ("drop", "系统行")),
        ("横幅正文", "恭喜海岸0030在助力榜飙升到第5名", ("drop", "系统行")),
        # 进房通知要**在药丸切之前**收走，否则「榜」正好落在前缀里（'通过主播热度榜'），
        # 药丸一切就得到一个像昵称的前缀 + 像正文的通知尾巴（实测 12 条这样的假评论）
        ("进房通知：两条并成一行",
         "昵称不能为空513通过主播热度榜进入直播间用户7994188615进入了直播间",
         ("drop", "系统行")),
        # 「进入直播间」被夹在中间 / 被 OCR 读花（进人具播间）/ 中间带空格 —— 都不锚行尾
        ("进房通知：OCR 读花且不在行尾",
         "落尽眼底通过直播预约进人具播间打茜油IUU通过具播预约进人具播间",
         ("drop", "系统行")),
        ("进房通知：中间带空格", "闻洒都脸红呀 通过 直播预约 进入 直播间",
         ("drop", "系统行")),
        # 点赞通知的 OCR 变体（「赞」读成「带」/被吃掉）—— 药丸那步认不出来，得系统行先判
        ("点赞通知：赞字被读成带", "能听哦的 为主播点带", ("drop", "系统行")),
        ("点赞通知：赞字被吃掉", "田户9039652824为主播点", ("drop", "系统行")),
    ]
    bad = [n for n, line, want in pill_cases
           if classify_line(line, rank_pill=True) != want]
    if bad:
        print(f"[selftest] 微博药丸断言失败：{bad}", file=sys.stderr)
        return False
    # 药丸是**版式装饰** —— 任何形状下都不许落进用户名或正文。这是用户报的第二条
    # （「榜一，榜二…不记录」）：把开关打开跑一遍全是药丸形状的行，输出里不该再有「榜」。
    leak = []
    for line in ("甜甜蜜995榜九：厉害呀", "用户6861943086榜二这车这么稳", "榜五这前脸一出来",
                 "用户6861943086榜一", "幸运女神的小新榜八秋名山女车神来了",
                 "杯酒交欢榜七支持这种不玩套路的品牌", "海岸0030榜", "榜二"):
        kind, payload = classify_line(line, rank_pill=True)
        if kind != "comment":
            continue
        name, content = payload
        if "榜" in (name or "") or "榜" in content:
            leak.append((line, name, content))
    if leak:
        print(f"[selftest] 药丸漏进输出：{leak}", file=sys.stderr)
        return False
    print(f"[selftest] 行文本规则 {len(cases) + len(pill_cases)} 项断言"
          f" + 药丸不泄漏 {8} 项断言通过 ✔")
    return True

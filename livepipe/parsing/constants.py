# --------------------------------------------------------------------------- #
# 3. 面板自动定位：先定出「该在哪 OCR」，再让 OCR 只跑在评论区内
# --------------------------------------------------------------------------- #
# 定位出来的矩形有两个身份：**语义区域**（评论区）和 **OCR 的裁切窗口**。后者才是
# 硬约束 —— 行不是矩形找出来的，是「行网格」在裁切图里找出来的，所以矩形必须
# ①完整包住整行（切进行里 ⇒ 整行丢，走不到任何下游，见 bug-209）
# ②不碰邻居（左面板上方是观众列表、右面板下方是输入框，进来就是垃圾行，见 bug-206）。
#
# 三种方法（实测对比见 .wolf/buglog.json 的 bug-206）：
#   model  —— 模型的「聊天面板」是**语义框**：x1 很准（575 / 1202，多次跑极差 3px），
#             但 y 不稳（同一素材两次跑给 y1=646 和 357），x2 干脆是整个窗口宽度。
#   ocr    —— 评论行几乎都是「昵称：正文」，冒号是最干净的判别特征：跨帧收「含冒号」
#             的行取并集即可，无歧义、不占 GPU、天然适配两个面板不同的高度。
#   hybrid —— x1 用模型、x2 用「内容右沿 + 余量」、y 全用内容。实测与手写矩形逐条一致。
#
# **两层拆分（定位面板 ⊥ 定位评论）**：矩形是**版式**、时不变；评论行是**内容**、逐帧变。
# 所以矩形由 ``locate_panel_rect`` 内容无关地给出（地板），评论行
# （``collect_comment_rows``）只在拿得到时做精修 —— 冒号只属于「认评论」这一层，跟解析侧
# 的 ``group_rows``（行网格，不看冒号）/ ``classify_line``（认评论，用冒号）同构。旧版把
# 两层粘在一起，于是「采样窗内没评论」被误判成「没有面板」（冷启动录屏丢面板的根因）。
DEFAULT_SPLIT_X = 1150          # 左右窗口分界（原图 x）：左 [0,1150]，右 [1150,2560]
DEFAULT_PANEL_MODEL = "nvidia/LocateAnything-3B"

# 评论区一定在窗口**下半部**（上半部是视频区 / 浏览器 chrome，不可能是评论）。评论行扫描
# （``collect_comment_rows``）和内容无关的兜底框（``locate_panel_rect``）共用这一条分界 ——
# 所以提成常量：两处若各写 0.45，改一处忘一处就会对不上。
COMMENT_SEARCH_FRAC = 0.45

PANEL_PROMPT = ("Locate all the instances that match the following description: "
                "chat comment list panel.")
# 输入框是**单个、小而独特**的元素，定位它比定位一个大区域稳定得多；它就在评论区
# 正下方，所以拿到它的上边界即可推出评论区下边界（--anchor input 用）。
PANEL_PROMPT_INPUT = ("Locate the region that matches the following description: "
                      "the message input box at the bottom of the chat panel.")

_BOX_RE = re.compile(r"<box><(\d+)><(\d+)><(\d+)><(\d+)></box>")

# 等级徽章列的宽度（原图 px）：正文起始 x（``x_text``）往左量这么多就是徽章列的左沿。
# 用途是 ROI 兜底 —— OCR 只在约一半的行上把徽章单独检出（小图标 + 小字号），
# 没检出时若只认检出的框，那些行的 ROI 就从昵称开始，等级标圈不进去。
# 这是**原图属性**（不随裁切变），所以直接拿已被重算成裁切内值的 ``x_text`` 减它。
#
# 宽度是**量出来的**，不是猜的（原图 t=0 左面板，胡杨那行逐列亮度剖面）：
#   x 575 ─ 577  徽章药丸左沿（= 自动定位拿到的面板左边界）
#   x 577 ─ 645  药丸本体（◆ 菱形 + 等级数字），宽 68
#   x 652 ─ 726  昵称「胡杨：」的墨迹（OCR 文字框 x1=652）
# 而 ``x_text`` 的绝对锚点是 633（手工面板 rect x1=563 + x_text=70）—— 它落在**药丸右端
# 内侧**，比昵称墨迹还靠左 19px。所以徽章列宽 = 633 - 575 = 58，不是药丸本身的 68。
# 取小不取大：58 让左面板的 badge_left 正好落在 575（面板裁切左沿），再大也只是被
# ``max(gx1, …)`` 夹回同一处，但换到别的 rect（含邻居 UI 的宽 rect）就会多圈进来。
#
# **默认值只对桌面网页版成立**。手机 App（``douyin_app``）的 ``x_text`` 是药丸右沿
# **外侧**（实测药丸墨迹 x∈[22,95]，x_text=96），58 只量到药丸中段 ⇒ ROI 左沿切在
# ◆ 菱形上，等级标圈不进去（实测 ROI x1=48、药丸左沿 38~40）。这类版式差异按平台档案
# 的 ``badge_span`` 覆盖（见 ``platforms.douyin_app.badge_span``），不动这里的常量 ——
# BADGE_SPAN 同时是徽章碎片判据的几何闸（见 ``_is_pill_fragment`` / ``_in_badge_gutter``），
# 改它会连带改变分组行为。
BADGE_SPAN = 58

# 「徽章药丸」这条横带相对 ``x_text`` 的实测偏移（裁切内 px）。要判「这块是不是徽章」，
# 只比 x1 是不够的 —— **折行续行**的文字也从 ``x_text`` 左边开始（它顶到面板左沿），
# 只按 x1 判就会把整条续行当徽章丢掉（bug-229）。
#
# 分界**只看左沿**就够，依据是两个互不重叠的实测区间（原图 t=240–300，30 帧，两个面板）：
#   折行续行  x1 ∈ [0..3]          顶在面板裁切左沿上
#   徽章碎片  x1 ∈ [12, 69]（左面板 x_text=58）/ [51, 112]（右面板 x_text=83）
# 取 ``x_text - BADGE_SPAN + BADGE_INSET``：左面板 = 8，夹在 3 与 12 之间；右面板 = 33，
# 夹在 3 与 51 之间。两边都分得开。
#
# **不要再加「右沿」条件**（曾经有过一条 ``x2 > x_text + BADGE_OVERHANG``）：徽章碎片的
# x1 已经 ≥12，光靠左沿就足以把它们排除；再加右沿只会误伤**短的**折行续行 —— 实测
# t=714 的续行 `下午好` x∈[3, 87]、宽 84px，x2 差 3px 够不到 ``x_text+32``=90，于是被判成
# 徽章碎片整行丢掉（用户报的现场）。宽窄是文字长度的函数，不是「是不是徽章」的函数。
BADGE_INSET = 8

# 「形状像整行」还不够 —— **左对齐的系统横幅**（``宋辉来了``、``必人77...闪亮登场``）
# 长得和折行续行一模一样（从面板左沿起、横跨到文字列里去、没有冒号），只按形状判就会
# 把横幅拼进上一条评论。真正的区别是**它跟上一行的间距**：
#
#   * 折行续行是**紧贴**在它首行下面的（浏览器按行高排版，只占约 0.63 个行距）；
#   * 横幅/通知行是**独立一行**，占满一个行距（实测 1.21–1.44 个行距）。
#
# 上沿取 0.73，依据是**全片** 194 个形状像折行的块的 gap/pitch 实测分布（不是抽样）：
#   同一行被 OCR 切开的碎片  0.007 / 0.029 / 0.029   （3 个，下沿管）
#   真续行                   0.324 … 0.669           （190 个）
#   孤立离群点               0.794                   （1 个 —— 见下）
#   左对齐横幅               1.213 … 1.441           （全片窗口实测）
# 0.73 落在 0.669 与 0.794 的几何中点（√(0.669·0.794)=0.729），两边各约 9% 余量；
# 离横幅下沿 1.213 还有 40% 余量，挡横幅的本职不受影响。
#
# 那个 0.794 的离群点（t=2240 ``头巴脑的``）是**假续行**：它上面一格坐着系统通知
# `36 余空鱼白加入了直播间`（通知行也带等级徽章、也从 x_text 起，形状上和评论首行分不开），
# 于是「上一行」够得着、间距又落在真续行（≤0.669）够不到的 0.79 —— 它的真首行其实
# 已经滚出面板顶了。放行它就变成一条正文 `头巴脑的`、用户名丢了的假评论（同一段文字在
# t=2238 已由 `生活多美好：…不整那` 正常续上，丢掉这条不损失任何内容）。
#
# **第二个平台也落在这条线上**（2026-10-12 接微博）：微博全量 16694 行里，折行的间距是
# 0.59~0.64（91 对）、而**紧随其后的那一行**（独立评论）是 0.97~1.01（86 对）—— 0.73
# 同样夹在两个簇中间（离折行上沿 0.09、离独立评论下沿 0.24 个行距），所以这条常数
# 不用按平台再调。微博走的是另一条**入口**（``panel["wrap_at_text_left"]``：
# 形状判据在微博上失效，只有间距分得开），闸门是同一个。
# 够不着上一行的（含面板顶端那种「上一行已滚出屏幕」的）按旧规则丢掉 —— 没有首行可拼，
# 留着只会变成一条「用户名丢了」的假评论。
WRAP_GAP_RATIO = 0.73

# 闸门还要有**下沿**：横幅 `言之有李来了` 会被 OCR 切成同一行的两块（`言之有李` x∈[578,805]
# + `来了` x∈[834,905]，y 中心只差 2px）—— 左边那块形状和续行一模一样，而它的「上一行」
# 就是同一行的 `来了`，间距 ≈0 ⇒ 从下沿溜过去，变成一条正文为 `言之有李` 的假评论（实测 3 条）。
# 全片 194 个形状像折行的块，gap/pitch 分布是两个分得很开的簇：
#   同一行被切开的碎片  0.007 / 0.029 / 0.029     （3 个）
#   真续行              0.324 … 0.669             （191 个）
# 10 倍的空档，下沿取 0.15（左面板 ≈10px）：离碎片上沿 5 倍、离真续行下沿 2 倍余量。
# 物理上也说得通 —— 行高约 30px、行距 68px，真续行必然落在首行下面大半个行距处，
# 不可能离上一行只有 10px。
WRAP_MIN_GAP_RATIO = 0.15

# 微博（``panel["wrap_at_text_left"]``）折行候选的 x 上沿：``x_text + 8``。
# 微博的折行是从**正文列左沿**起的（不像抖音贴面板裁切左沿、也不像抖音手机版缩进），
# 所以候选只能按「从正文列左沿起」认 —— 上沿要容下 OCR 在**首字**上的抖动。
# 量过的证据（``out/weibo_run/rows.jsonl`` 全量 16694 行 / 1418 帧，2026-10-12）：
#   · 91 对真折行（间距 0.59~0.64 个行距，见 ``WRAP_GAP_RATIO``）的**首块** x1 ∈ [38, 43]，
#     而同一面板的 ``x_text`` = 38 ⇒ 最大右偏 5px；
#   · 独立评论的首块 x1 ∈ [38, 45] —— 与折行**完全重叠**（这是「微博不能用形状判续行」的
#     直接证据，所以这些候选落进 ``rows`` 后由**间距**判去留，见 ``_text_left_candidates``）。
# 取 8：离实测最大右偏（5）还有 3px 余量；再往上放没有收益（候选多出来的只是白跑一次
# 间距闸），往下收（比如 5）会把首字抖动到 43 的那两条折行漏在门外。
WRAP_TEXT_LEFT_SLACK = 8

# 「右端条带」：面板右侧这一比例以右的文字块。评论的正文列在**左边**（昵称贴左、正文在其右），
# 所以能落进右端条带的只有浮层 / 水印 / logo —— 见 ``group_rows`` 里那条「纯 ASCII 短碎片」过滤。
OVERLAY_STRIP_FRAC = 0.75

# 「纯 ASCII 短碎片」：整行是**一个** ASCII 词、且很短（无空格、无汉字、无 emoji）。
#
# 这类行在 ``classify_line`` 里会落进「续行」分支（没有冒号 ⇒ 不像评论首行），而续行分支
# **故意不丢**（bug-229 的教训：匿名行多是「用户名被 OCR 丢了」的真评论，丢了就是真丢数据）。
# 但水印不是评论：现场实测视频号画面右上角的品牌水印被 OCR 读成 ``CHER`` / ``CHERY``
# （x=2421、42×8px 的小碎片），落进行槽就变成一条 ``{"username": null, "content": "CHER"}``
# 的匿名评论 —— 还会被当验收图里的一个框画出来，看着像「系统行被当成评论了」。
#
# 只收「**单个**词」是关键：带空格的英文续行（``very nice``）不在这个形状里，中文续行必有
# 汉字 —— 真正会误伤的只剩「恰好是一个英文单词的续行」，在这些中文直播语料里基本不存在。
# 而且**必须和「落在右端条带」一起用**（见 ``OVERLAY_STRIP_FRAC``）：正文列里的短英文词照旧
# 保留，单看内容形状不敢丢。
ASCII_FRAGMENT_RE = re.compile(r"^[A-Za-z][A-Za-z0-9]{0,7}$")

# 「一个槽里并了两行」的判据：**行框高 > 行距 × 这个比例** ⇒ 这不是一行，是两行。
# 单行框高实测 22~36px（行距 54），两行并块 78~84px（≈1.5 个行距 + 字高）。取 1.3 是两头
# 留余量：单行再高到不了 1.3 个行距，两行再挤也低不下去。见 ``split_fused_rows``。
TALL_BLOCK_FRAC = 1.3

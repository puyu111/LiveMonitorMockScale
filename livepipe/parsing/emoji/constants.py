from __future__ import annotations



# --------------------------------------------------------------------------- #
# 4. 表情识别：像素 → 表情 token（按面板选表，官方资产的模板匹配）
# --------------------------------------------------------------------------- #
# 评论里的「表情」有两类：
#   ① **平台官方表情**：身份是平台自己定义的 token（``[赞]``/``[强]``），表在 ``out/``：
#      抖音 214 个（身份 = 图床对象名里那段 32 位 hash，``livepipe/douyin_emoji_table.py --api``）；
#      微信 2021 新版 109 个（没有 hash，身份 = 顺序号 001~109，``livepipe/wechat_emoji_table.py``）；
#      微博 338 个（身份 = 面板 key / CDN stem，``livepipe/weibo_emoji_table.py --config``；
#      注意微博那张表的 thresholds 只是**部分标定**（只有 ``[打call]`` 一种字形），换素材先量）；
#      快手 App 207 个（身份 = ``001_名称``，``livepipe/kuaishou_emoji_table.py``；
#      阈值在 590×1280 App 录屏上量过：真表情 0.845~0.964、纯文字最高 0.80）；
#   ② 用户在系统键盘上敲的 **Unicode emoji**（👍❤️🔥，字形由录屏那台机器的字体渲染）。
# 这一段只做 ① —— 录屏里拿不到 DOM，只有像素，所以官方表情的身份是**匹配**出来的：
# 把官方图（带 alpha，先合成到聊天背景色上）缩到与画面同高，算归一化互相关（NCC）取 top-1。
#
# **一个录屏里可能有不止一个源**：本素材就是两个浏览器窗口并排，左边抖音、右边视频号，
# 两边的表情是两套完全不同的资产（抖音那个 👍 是 ``[赞]`` 粉色袖口，微信那个 👍 是
# ``[强]`` 绿色袖口）。拿错表不会「分数低一点」，而是**一个都认不出来**（跨表实测最高
# 0.670/0.756，而正确表 0.876）。所以表是**按面板**选的（``--emoji-table``，见
# ``parse_emoji_tables``），阈值也跟着表走（见 DEFAULT_THRESHOLDS 的说明）。
# 没被 ① 覆盖的那部分（微信侧也有 Unicode emoji）现在**不认**，产物里就是「没有表情」。
#
# 为什么不用 OCR 框当表情框（同 bug-214 的教训）：表情不在 OCR 的识别对象里，框的边界
# 与表情无关 —— 实测蓝爵那条 ``text_box`` 的 x2=882 盖住了 x∈[832,912] 的两个表情。
# 所以表情区是**按像素扫**的：``x_text``（徽章列之右）到面板右边，整条行带。
#
# 阈值分工不同（都是**按源量出来**的，见 DEFAULT_THRESHOLDS 与每张表的 thresholds 块）：
#   * ``coarse_min`` ⇒ 半尺寸粗筛**提议**位置（宁松勿严，位置最终由精验定）；
#   * ``looks_like`` ⇒ 像不像表情。整块文字（白/青字）跟表里所有模板的 NCC 都低，
#     到不了这条线就直接丢，不上报 —— 所以不需要另写「这里是不是文字」的判据。
#   * ``min_score``  ⇒ 敢写 token 的门槛；
#   * ``min_margin`` ⇒ 表里有形近对（抖音 ``[赞]``/``[点赞]``、``[爱心]``/``[比心]``/
#     ``[送心]``；微信 ``[爱心]``/``[心碎]``、``[擦汗]``/``[汗]``）。实测松框匹配会把 ❤️
#     认成 ``[比心]``（0.769 vs 0.744）——**宁可交 ``token: null`` + ``guess``，也别交错
#     token**。
# margin 必须拿**全表在同一位置重算**（``_token_scores_near``），不能拿粗筛候选 ——
# 用一个低阈值看原始分布时，杂项一水儿是同一表情被 NMS 漏掉的偏移重检，分数 0.5 一档；
# 这类杂项就是「阈值定错了」的报警器，定完阈值它们全消失（实测 284 → 87）。
EMOJI_BG = (37, 36, 50)              # 聊天区背景（RGB）：alpha 图得合成到它上面才和画面可比
EMOJI_HEIGHT_RATIO = 0.56            # 表情渲染高 ≈ 0.56 × 行距（pitch 68 → 38px，实测 36~40）
# 表的选择**按面板**给：这个录屏是两个窗口并排，左边抖音、右边视频号的评论区 ——
# 两边的表情**不是同一套资产**（抖音 214 个官方表情；视频号用微信 2021 新版 109 个），
# 拿错表不是「分数低一点」而是「一个都认不出来」（见 thresholds 的说明）。
# 写法（逗号分隔，可重复）：``面板=表路径或源名``，或整段只给一个值表示所有面板都用它。
# 源名在 SOURCE_TABLES 里查（douyin / wechat / weibo），省得每次抄路径。
DEFAULT_EMOJI_TABLE = "left=douyin,right=wechat"
# 源 id → 表的默认路径（``--emoji-table left=douyin`` 里的 douyin 就查这里）
SOURCE_TABLES = {
    "douyin": "out/douyin_emoji/douyin-emoji.json",
    "wechat": "out/wechat_emoji/wechat-emoji.json",
    # 微博：面板 key 当身份（``byId``），图在 img/<序号_名称>.<png|gif>。
    # **阈值没标定**：那份表里的 thresholds 是照视频号抄的起点值（微博侧还没有录屏可量），
    # 拿它跑微博素材前先按下面的「报警器」流程量一遍，否则表现是静默丢光。
    "weibo": "out/weibo_emoji/weibo-emoji.json",
    # 快手 App：身份是 ``001_名称``（token 来自 live.kuaishou.com 的 emojiPanel），
    # 图在 img/<id>.png；阈值 2026-11-03 在 590×1280 App 录屏上量过（真表情 0.845~0.964）。
    "kuaishou": "out/kuaishou_emoji/kuaishou-emoji.json",
}
# 阈值是**量出来的**：把全素材 56 行的原始命中分数拉出来看，分布是干净的双峰 ——
# 真表情 87 个全在 0.90 以上（多数 ≥0.95），杂项 197 个全在 0.65 以下，0.65~0.90 之间
# **一个都没有**。所以「像不像表情」的线放在山谷里随便哪都行，取 0.78 只求两边都留余量：
# 换素材时真表情掉几分、杂项涨几分都不会翻车。杂项是什么：文字块、被 NMS 漏掉的
# 同一个表情的偏移重检（真表情的同款重复在 0.95+，杂项是 0.5 一档的「像但不完全像」）。
#
# **阈值必须按表走，不能当全局常量。** 上面这套数字是**抖音侧**量的：抖音的表情是官方
# 无损 webp 原生渲染，所以能要求 0.85。换到视频号（微信 2021 新版 109 个）就不成立 ——
# 那边表里是 128px 的 PNG，被渲染成 ~30px 再录屏压一道，真表情最高 0.876、多数 0.68~0.83。
# 拿抖音那组数去卡视频号，结果是**全部静默丢掉**，产物看起来像「这一屏没有表情」——
# 这是最难查的一种错（产物合法、也不报错）。所以阈值跟表走：
# ``表里的 thresholds`` > ``这里的默认``；表没带 thresholds 就**出声警告**再用默认值。
DEFAULT_THRESHOLDS: dict[str, float | int] = {
    "height_ratio": EMOJI_HEIGHT_RATIO,  # 表情高 = ratio × 行距（左面板 0.56→38px）
    "looks_like": 0.78,              # 低于它 ⇒ 不是表情，丢掉
    "min_score": 0.85,               # ≥ 它 + margin 够 ⇒ 认这个 token（真表情实测 ≥0.90）
    "min_margin": 0.10,              # 与**别的 token**的最好成绩之差（真表情 0.16~0.37，杂项 ≤0.06）
    "coarse_min": 0.55,              # 半尺寸粗筛的阈值（宁松勿严：粗筛只负责**提议**位置）
    "coarse_cap": 400,               # 粗筛候选点数上限（按分数取前 N，防长条带爆炸）
    # 候选框内的平均饱和度（HSV 的 S，0~255）。**只在「分数不够命名」时当兜底**：
    # 官方表情是彩色位图，聊天区文字（昵称/正文/系统公告）是白/浅色 ⇒ S≈0。
    # 整块文字跟某些表情模板的 NCC 能到 0.75~0.82（微博实测 `车` 对 `[林致]` 0.765，
    # 一屏公告里 274 次），光看分数分不开；颜色是一眼就分开的（实测真表情 ≥111、白字 0）。
    # 0 = 关（老表行为不变）；按源量过再开（微博表 30）。
    "min_saturation": 0.0,
}
# 兼容别名：这几个名字是旧版遗留，**只是 DEFAULT_THRESHOLDS 的展开，别再单独引用**
# （阈值现在按表走；改这里的数不会影响任何一张带 thresholds 的表）
EMOJI_LOOKS_LIKE = DEFAULT_THRESHOLDS["looks_like"]
EMOJI_MIN_SCORE = DEFAULT_THRESHOLDS["min_score"]
EMOJI_MIN_MARGIN = DEFAULT_THRESHOLDS["min_margin"]
EMOJI_COARSE_MIN = DEFAULT_THRESHOLDS["coarse_min"]
EMOJI_COARSE_CAP = DEFAULT_THRESHOLDS["coarse_cap"]

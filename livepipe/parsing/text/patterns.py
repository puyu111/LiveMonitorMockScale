"""livepipe.parsing.text.patterns — 从 parse_live_comments.py 拆出的同源实现。"""

from __future__ import annotations

import re


# --------------------------------------------------------------------------- #
# 1. 文本规则：判据只有这一套（parse 与 report 共用）
# --------------------------------------------------------------------------- #
# 冒号：中英文都认。
_COLON_RE = re.compile(r"[:：]")

# 续行必须比首行**右移多少像素**才算「折行缩进」（``_indented_continuation``）。
# 量过的证据：
#   · 微博昵称列左沿实测 x1 ∈ [34, 48]，**同帧内**的极差 median 4 / p99 8 / max 9 ——
#     这是 OCR 框在昵称首字上的抖动，不是缩进；
#   · 抖音竖屏真续行缩进到正文列：x1=128 而首行 x_text=70 ⇒ 右移 58。
# 取 12：离抖动上限（9）还有 3px 余量，离真缩进（58）差着近 5 倍。改之前微博上
# 「右移 1~2px」就被当成折行缩进 ⇒ 一整屏互不相干的评论被并成一条（本次要修的 bug）。
_INDENT_MIN_PX = 12

# 缩进续行的**间距上沿**：这一行离上一条评论的**最后一行**最多几个行距（``_indented_continuation``）。
# 光有「缩进」不够 —— 昵称被 OCR 整块吃掉时（视频号把昵称打码成 `**`，有些帧一个星号都没读出来），
# **独立评论**的正文正好落在昵称列右边，形状和折行一模一样，只能按**间距**分：
#   · 真折行紧贴首行：实测三套语料 0.32~0.76 个行距（抖音网页 0.324~0.669、微博 0.59~0.64、
#     手机 App 版 0.74~0.76，见 ``WRAP_GAP_RATIO``），上沿 0.76；
#   · 独立评论按**行网格**排：间距 ≈ 一个整行距（微博全量 86 对 0.97~1.01）。
# 取 0.85：离真折行上沿 0.09、离独立评论下沿 0.11 —— 两边最宽的空档中间。
#
# 加闸前后在**六套语料**上逐条 diff 过（`--rows` 复算，闸开 vs 闸关，其余参数完全一致）：
# 只有「缩进成立且没被掩码昵称挡下」的候选受影响，共 **418 对**被挡（= 恢复成两条独立评论），
# 其中 395 对落在 1.0 个行距、3 对 0.9、20 对 ≥1.1 —— **0.76~0.85 之间一对都没有**，
# 也就是没有一对真折行被误挡（最靠近闸门的 3 对逐条看过，都是语义独立的短评论：
# `666` + `CCCC`、`岑岑~黎平奇瑞汽车` + `牛十`）。微博那 17 对尤其说明问题：`榜N` 药丸
# 是**另一个人**的名次标（`打酱油100：奇瑞这两年车型设计进步太大了` + `榜二老牌子整新活，有点意思`），
# 旧的形状判据把它们并进了上一条。
_INDENT_MAX_GAP_RATIO = 0.85

# 系统行的**残句尾巴**：整段公告被折行切开后，最后一块可能只剩两三个字（实测「失。」，
# 是「…以防人身财产损失。」的尾巴）。它自己不含任何上表里的短语 ⇒ 只能按**形状**认，
# 但形状本身不够 —— 全量抖音语料里「无冒号 + ≤4 字 + 以句末标点结尾」的行有 27/56 条是
# **真评论的折行残片**（'看。' '造。' '得真好！' '赴山海！'），只按形状丢就是真丢数据。
# 所以这条只在**紧跟在一条系统行之后**（``parse_live_rows`` 里判）才生效。
_TAIL_FRAGMENT_RE = re.compile(r"[。！？!?]\s*$")
_TAIL_FRAGMENT_MAX = 4

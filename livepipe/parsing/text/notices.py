"""livepipe.parsing.text.notices — 从 parse_live_comments.py 拆出的同源实现。"""

from __future__ import annotations

from functools import lru_cache
import re



_NOTICE_RE = re.compile(
    r"赞了直播|为主播点赞|入了直播间|关注了主播|送出了?"
    r"|在线观众|贡献用户|高等级用户"
)
# 抖音的进房通知「X来了」（整行以「来了」收尾）。**单拎出来** —— 它跟上面那串短语不是
# 一回事：上面每条都是抖音专有词，而「来了$」认的是**形状**，真评论里
# 「…要支棱起来了」「秋名山女车神来了」全是这个形状。微博实测 199 行命中它，
# **没有一行是进房通知**（微博的进房通知是「X 通过 直播预约 进入直播间」，走
# _NOCOLON_NOTICE_RE），整条真评论被静默丢掉。所以药丸面板（微博）不走这条 ——
# 见 ``classify_line`` 的 ``rank_pill`` 分支。
_ENTER_RE = re.compile(r"来了\s*$")
# 底部 / 顶部提示：不是评论，**也不该被当成续行**。
_FOOTER_RE = re.compile(r"需先登录|才能开始聊天|先登录|聊一聊|^\s*全部\s*$")

# 微博 App 的**系统行**：横幅 + 通知 + 开播公告。它们的共同点是**都没有冒号**
# （左对齐整行），所以上面那套按短语认抖音通知的正则一条也认不出来，全被当匿名评论 /
# 续行收进来了（实测 t=300 两行通知被并成一条 30 字的「评论」，t=0~120 的开播公告被
# 拆成 4 条匿名评论）。实测三类的样子：
#   · 横幅「恭喜 X 在助力榜飙升到第N名」+ 右侧药丸按钮「我也上榜」（列表里混着药丸，
#     它自己也是一个 OCR 块 ⇒ 一行只剩「我也上榜」）
#   · 通知「X 通过 直播预约 进入直播间」/「用户NNN进入直播间」（多半以「进入直播间」收尾，
#     **但不能锚行尾**，见下）
#   · 开播公告「欢迎使用微博直播服务。微博直播禁止包含色情、违法、侵权等性质内容，
#     对于发布违规内容的用户，微博站方将采取禁言或封号等管理手段。购买商品请点击
#     购物袋按钮，请勿私下交易，请谨慎判断以防人身财产损失。」
# **只在没有冒号时启用这一组**：有冒号 ⇒ 这行是「昵称：正文」，正文里写「进入直播间」
# 完全是正常评论，不能连坐。
# 短语表是**量过的**：全量抖音语料（out/comments_merged_v2 39717 行 + out/livepipe_example3
# 43319 行）里「无冒号 且 命中本表」的行数都是 **0** ⇒ 加它不会动已交付的抖音语料。
#
# 进房通知那一条取核心词「播间」而**不锚行尾**，两条都是量出来的（out/weibo_run/rows.jsonl
# 16694 行，2026-10-11）：
#   · 锚行尾会漏：OCR 把两条通知并成一行、或行尾那截被吃掉时，「进入直播间」不在行尾 ——
#     实测含「进入直播间」却不在行尾的 14 行，**带冒号的 0 行**（全是通知）。锚着行尾时
#     这 14 行就从上面那条缝里漏过去，落到**药丸拆分**那一步：`榜` 正好落在 '通过主播热度榜'
#     这截前缀里，一切得到「像昵称的前缀 + 像正文的通知尾巴」（药丸排在 `_NOTICE_RE` 之前，
#     见 ``classify_line`` 的 rank_pill 分支，bug-330）。复算时实测 13 条这样的假评论，其中
#     2 条还带假昵称（用户名 '昵称不能为空513通过主播热度'、正文 '进入直播间用户7994188615
#     进入了直播间'）。
#   · 取「播间」：无冒号 且 含「播间」的行 445 行，逐条看过**全是进房通知**（407 行
#     精确「进入直播间」/ 32 行 OCR 变体「进人具播间」这类 / 6 行带空格或夹字
#     '进入 直播间'、'进入7直播间'），**0 行真评论**。
#   · 抖音动不了：两套语料里「无冒号 且 含播间」的行 1398 / 1681 行，照样全是
#     「X加入了直播间」—— 它们在非药丸分支里早被 _NOTICE_RE 的「入了直播间」收走了，
#     这一条对抖音是空操作（全量 diff 验过：6296 / 6855 字节不变）。
# 代价（已知、量过、认下）：无冒号**又**在正文里提「直播间」的真评论会被误丢，全量语料里
# 0 条。真出现了再加形状判据（「(通过…)?(进入|加入了)直播间」），别现在为了假想输入放宽。
#
# 「为主播点」那条是同一类的补丁（微博的「X 为主播点赞」通知）：`_NOTICE_RE` 在**药丸面板**
# 里排在药丸之后，而这几行没有药丸、也认不出昵称，于是漏成匿名评论。量过的边界：
#   · 微博：无冒号 且 含「为主播点」的 5 行**全是通知**（OCR 把「赞」读成「带」或整字吃掉：
#     '能听哦的 为主播点带' 'M719229131为主播点带' '田户9039652824为主播点'）;
#   · 抖音：含「为主播点」却**有冒号**的 3 / 5 行是真评论（'…上门服务：为主播点'），
#     本表只在无冒号时启用 ⇒ 一条都碰不到（全量 diff 验过字节不变）。
_NOCOLON_NOTICE_RE = re.compile(
    r"播间"                               # 进房通知「X 通过 直播预约 进入直播间」，不锚行尾
    r"|为主播点"                          # 点赞通知（「赞」被 OCR 读成「带」或吃掉）
    r"|我也上榜"                          # 横幅右侧药丸按钮（整行就是它）
    r"|助力榜"                            # 横幅正文「恭喜 X 在助力榜飙升到第N名」
    r"|微博直播服务|微博直播禁止|微博站方"   # 开播公告（整段会被折行切成几块）
    r"|禁言或封号|违规内容|物袋按钮|购物袋|私下交易|人身财产损"
)

# 视频号手机 App 的**浮层卡**：压在评论列表上的 UI 卡片 / 广告气泡。它们不是评论，但长在
# 评论 rect 里、又没有冒号，于是被当匿名评论收进来（实测 2026-10-12 CTCC 素材：seg1 的
# 90s 样本里 172 行有 140 行是「通知 + 平台提示」两张卡，t=0 那帧产出的 3 条「评论」
# **全是卡**）。`_NOCOLON_NOTICE_RE` 那套只认微博，一条都认不出它们。
#
# 四类的样子（短语取的都是**卡片自己折行后每一块里都还在**的词，不取整句）：
#   · 平台提示卡：「色情低俗、诱导欺诈、抽烟酗酒等内容。请谨慎判断，理性消费，避免财产
#     及人身损失，发现违规行为请及时投诉。」——被折行切成 3 块 ⇒ 诱导欺诈 · 抽烟酗酒 ·
#     理性消费 · 人身损失 · 及时投诉 各认一块；
#   · 主题卡 / 公众号卡：行首就是卡片自己的标签（`主题CTCC职业联赛鄂尔多斯站`、
#     `公众号奇瑞汽车>`），**锚行首**认「主题」「公众号」两个字；
#   · 广告气泡：CTA「点击了解详情」（OCR 常把「点」读成「占」）。
# 主题卡第二行（`2026CTCC中国汽车场地职业联赛`）和广告气泡的品牌行（`奇瑞汽车`）
# **没有任何特征词** —— 按内容赌会误伤真评论（真评论完全可能提「奇瑞汽车」），所以它们
# 靠解析层的**卡片续行**规则吃掉（见 ``parse_live_rows``），不在这里认。
#
# 两重闸：只在**没有冒号**的行上生效（有冒号 ⇒ 这就是「昵称：正文」，连坐不得），
# 且只在配了 ``overlay_cards`` 的**面板**上生效（平台档案字段，见 ``platforms.wechat_app``）。
# 抖音/微博的面板不开它 ⇒ 那两套语料行为一字不变（量过：三套已交付语料的无冒号行命中
# 本表 **0** 行，加它本来就是空操作，挂平台开关只是把「这是视频号的版式事实」写明白）。
#
# **内置表只放「跟素材无关」的短语**。带品牌名的那类（广告气泡的品牌行 `奇瑞汽车`）**不放**
# —— 量过：`奇瑞汽车` 在三套已交付语料的无冒号行里命中 25/40 行，全是真评论的折行续行
# （`奇瑞汽车老品牌，值得信赖`）。这类词挂在**素材配置**上（``"overlay_cards": "<额外正则>"``，
# 见 ctcc.json 的 platforms.wechat_app），由 ``overlay_card_re`` 与内置表合成。
_OVERLAY_CARD_RE = re.compile(
    r"诱导欺诈|抽烟酗酒|理性消费|人身损失|及时投诉"     # 平台提示卡（折行后每块各命中一个）
    r"|色情低俗|欢迎来到直播间"                        # 提示卡首块 · 开屏公告
    r"|^\s*主题"                                     # 主题卡（行首标签）
    r"|^\s*公众号"                                   # 公众号卡（行首标签）
    r"|点击了解详情|占击了解详情|了解详情"               # 广告气泡的 CTA
)


@lru_cache(maxsize=32)
def overlay_card_re(extra: str | None = None) -> re.Pattern:
    """浮层卡判据 = 内置表 ``_OVERLAY_CARD_RE`` **＋本素材补的短语** ``extra``。

    ``extra`` 就是平台档案里 ``overlay_cards`` 给**字符串**时的取值（正则片段，见
    ``platforms.wechat_app`` 的注释）；给 ``True``/缺省 ⇒ 只有内置表。

    为什么要开这个口子：内置表只认「跟素材无关」的 UI 短语，而广告气泡的**品牌行**
    （`奇瑞汽车`，OCR 把「广告」标签吃掉、只剩品牌名）没有任何通用特征词，按内容猜会
    误伤真评论（`奇瑞汽车老品牌，值得信赖` 这种折行续行在三套语料里有 25/40 行）。
    素材级的短语写在**素材配置**里，跟它量出来的那批帧待在一起，换素材时一眼能看出该改哪。
    缓存：同一个正则只编译一次（``classify_line`` 每行都要查它）。
    """
    if not extra:
        return _OVERLAY_CARD_RE
    return re.compile(f"{_OVERLAY_CARD_RE.pattern}|(?:{extra})")

# 「掩码昵称」开头的行（``**：正文`` / ``柠檬*：正文`` / ``A***分享了直播``）。
# 平台把昵称中间打码成 ``*``：抖音打 3 颗（``A***``），视频号打 1~2 颗（``柠檬*``、``一**``）。
# 拿它当**否定**判据用（见 ``_indented_continuation``）：续行是正文，正文不会以掩码昵称开头。
#
# 为什么是 ``{2,}`` 而不是跟着抖音写 ``***``：视频号这帧实测的漏判就是两颗星 ——
# ``**.线下有品鉴会就好了``（冒号被 OCR 读成 ``.`` ⇒ 没有冒号 ⇒ 续行候选），旧判据要
# 3 颗星，挡不住它，于是被并进上一条 ``萌萌：五站八冠，这统治力可以`` 的正文里。
# 为什么**不**放宽到 1 颗：单星后面跟正文字符（``*这车真好看*`` 这类以星号开头的续行）
# 会被误挡 —— 要求 ≥2 颗是最小的、能覆盖两个平台掩码形态的宽度。
_MASKED_NAME_RE = re.compile(r"^\S*\*{2,}")

# 同上，但**后面紧跟分隔符**（``**：正文`` 的冒号被 OCR 读成 ``.`` / ``，`` / ``·`` 等）。
# 这一族能确定「星号是昵称、后面才是正文」，所以 ``classify_line`` 直接把它判成**匿名评论**
# 并把掩码前缀剥掉（不剥的话正文里会粘着一个 ``**.``，见 ``_MASKED_NAME_RE`` 那段实测）。
_MASKED_NAME_LINE_RE = re.compile(r"^\S*\*{2,}\s*[：:．.·•。、,，]")
